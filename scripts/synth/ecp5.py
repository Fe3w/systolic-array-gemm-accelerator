#!/usr/bin/env python3
"""ECP5 synthesis + place-and-route for one SysArray top (M7, D-020).

Two Yosys runs and one nextpnr run per top:

1. **Resources** - `synth_ecp5` of the bare top; `stat -json` gives the cell
   counts reported as `yosys_cells` (the design itself, nothing added).
2. **Timing** - the top is wrapped in a generated measurement harness
   (`build/synth/<name>/synth_wrap.v`, not part of rtl/): every input bit comes
   from a 1-pin shift register, every output bit is registered and XOR-reduced
   through a pipelined tree of 4-input XORs (one LUT level per stage) into
   1 pin; `clk` and `rst` are real pins. This keeps all logic observable and
   makes the design fit the package (S = 8 `sa_array` alone has ~390 port bits)
   while every timed path inside the design starts and ends at a register.
   `synth_ecp5` -> nextpnr-ecp5 (LFE5U-85F, CABGA381, speed 6), target clock,
   fixed placer seed, `--report`. `nextpnr_utilization` therefore *includes*
   the harness; `harness` records its size.

Outputs: results/synth/<top>_S<S>_<sha>.json, and raw/<name>/ with yosys_stat.json,
nextpnr.log and nextpnr_report.json.gz (full Yosys logs stay in build/synth/).
Usage (repo root): python3 scripts/synth/ecp5.py --top sa_array --S 8 [--freq 100] [--seed 1]
nextpnr: native `nextpnr-ecp5` if on PATH, else `yowasp-nextpnr-ecp5` (PyPI, D-013a).
"""

from __future__ import annotations

import argparse
import gzip
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEVICE = {"family": "ECP5", "part": "LFE5U-85F", "package": "CABGA381", "speed": 6}
KEEP_CELLS = ("LUT4", "TRELLIS_FF", "CCU2C", "MULT18X18D", "ALU54B", "DP16KD",
              "PFUMX", "L6MUX21", "TRELLIS_DPR16X4")  # fmt: skip
KEEP_UTIL = ("TRELLIS_COMB", "TRELLIS_FF", "MULT18X18D", "ALU54B", "DP16KD", "TRELLIS_IO",
             "TRELLIS_RAMW")  # fmt: skip


def sh(cmd: list[str], log: Path) -> None:
    res = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    log.write_text(res.stdout + res.stderr)
    if res.returncode != 0:
        tail = "\n".join((res.stdout + res.stderr).splitlines()[-30:])
        raise SystemExit(f"command failed ({res.returncode}): {' '.join(cmd[:3])} ...\n{tail}")


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True).stdout.strip()


def git_commit() -> str:
    dirty = git("status", "--porcelain", "--", "rtl", "scripts/synth")
    return git("rev-parse", "--short", "HEAD") + ("-dirty" if dirty else "")


def tool_version(cmd: list[str]) -> str:
    out = subprocess.run(cmd, capture_output=True, text=True)
    lines = (out.stdout + out.stderr).strip().splitlines()
    return lines[-1][:120] if lines else "unknown"


def rtl_sources() -> list[str]:
    sources = sorted(str(p.relative_to(REPO)) for p in (REPO / "rtl").rglob("*.sv"))
    return [s for s in sources if s.endswith("_pkg.sv")] + [
        s for s in sources if not s.endswith("_pkg.sv")
    ]


def harness(top: str, s: int, ports: dict) -> tuple[str, dict[str, int]]:
    """Verilog for the measurement wrapper, plus its size in bits."""
    ins = [(n, len(p["bits"])) for n, p in ports.items()
           if p["direction"] == "input" and n not in ("clk", "rst")]  # fmt: skip
    outs = [(n, len(p["bits"])) for n, p in ports.items() if p["direction"] == "output"]
    n_in, n_out = sum(w for _, w in ins), sum(w for _, w in outs)
    lines = [
        "// Generated by scripts/synth/ecp5.py: timing harness, not part of the design.",
        "module synth_wrap (input wire clk, input wire rst, input wire din, output wire dout);",
        f"  reg [{n_in - 1}:0] sin;",
        (
            f"  always @(posedge clk) sin <= {{sin[{n_in - 2}:0], din}};"
            if n_in > 1
            else "  always @(posedge clk) sin <= din;"
        ),
        f"  wire [{n_out - 1}:0] o;",
        f"  reg [{n_out - 1}:0] o_q;",
        "  always @(posedge clk) o_q <= o;",
    ]
    conns, lo = [".clk(clk)"], 0
    if "rst" in ports:
        conns.append(".rst(rst)")
    for n, w in ins:
        conns.append(f".{n}(sin[{lo + w - 1}:{lo}])")
        lo += w
    lo = 0
    for n, w in outs:
        conns.append(f".{n}(o[{lo + w - 1}:{lo}])")
        lo += w
    params = f" #(.S({s}))" if s > 0 else ""
    lines.append(f"  {top}{params} u_dut ({', '.join(conns)});")
    # Pipelined XOR reduction: each stage XORs groups of 4 and registers them.
    width, src, stage, red_regs = n_out, "o_q", 0, 0
    while width > 1:
        nxt = (width + 3) // 4
        lines.append(f"  reg [{nxt - 1}:0] x{stage};")
        terms = []
        for g in range(nxt):
            bits = [f"{src}[{i}]" for i in range(4 * g, min(4 * g + 4, width))]
            terms.append(f"    x{stage}[{g}] <= {' ^ '.join(bits)};")
        lines.append("  always @(posedge clk) begin\n" + "\n".join(terms) + "\n  end")
        red_regs += nxt
        width, src, stage = nxt, f"x{stage}", stage + 1
    lines.append(f"  assign dout = {src}[0];" if n_out > 1 else "  assign dout = o_q[0];")
    lines.append("endmodule")
    size = {"input_shift_ffs": n_in, "output_ffs": n_out, "xor_tree_ffs": red_regs,
            "xor_stages": stage}  # fmt: skip
    return "\n".join(lines) + "\n", size


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--top", required=True)
    ap.add_argument("--S", type=int, default=8, help="array side; 0 for tops without S (sa_pe)")
    ap.add_argument("--freq", type=float, default=100.0, help="target clock in MHz")
    ap.add_argument("--seed", type=int, default=1, help="nextpnr placer seed")
    args = ap.parse_args()

    commit = git_commit()
    # Seed 1 keeps the M7 file names; other seeds get a suffix so runs don't overwrite.
    name = f"{args.top}_S{args.S}_{commit}" + (f"_seed{args.seed}" if args.seed != 1 else "")
    raw = REPO / "results" / "synth" / "raw" / name
    work = REPO / "build" / "synth" / name
    raw.mkdir(parents=True, exist_ok=True)
    work.mkdir(parents=True, exist_ok=True)
    # SA_ECP5_DSP: sa_pe's stage-1 register is the MULT18X18D output register (M11b).
    read = (
        "read_verilog -lib +/ecp5/cells_bb.v; "
        f"read_verilog -sv -DSA_ECP5_DSP {' '.join(rtl_sources())}; "
    )
    chparam = f"chparam -set S {args.S} {args.top}; " if args.S > 0 else ""

    # 1. Resources of the bare top, and its port list.
    sh(["yosys", "-q", "-l", str(work / "yosys_bare.log"), "-p",
        read + chparam + f"hierarchy -top {args.top}; proc; write_json {work / 'ports.json'}; "
        f"synth_ecp5 -top {args.top}; tee -q -o {raw / 'yosys_stat.json'} stat -json"],
       work / "yosys_bare.out")  # fmt: skip
    ports = json.loads((work / "ports.json").read_text())["modules"][args.top]["ports"]
    wrap_v, wrap_size = harness(args.top, args.S, ports)
    (work / "synth_wrap.v").write_text(wrap_v)

    # 2. Timing: harness + top through synthesis and place-and-route.
    netlist = work / "netlist.json"
    sh(["yosys", "-q", "-l", str(work / "yosys_wrap.log"), "-p",
        read + chparam + f"read_verilog {work / 'synth_wrap.v'}; "
        f"synth_ecp5 -top synth_wrap -json {netlist}"],
       work / "yosys_wrap.out")  # fmt: skip
    nextpnr = "nextpnr-ecp5" if shutil.which("nextpnr-ecp5") else "yowasp-nextpnr-ecp5"
    report = raw / "nextpnr_report.json"
    sh([nextpnr, "--85k", "--package", DEVICE["package"], "--speed", str(DEVICE["speed"]),
        "--json", str(netlist), "--freq", str(args.freq), "--seed", str(args.seed),
        "--lpf-allow-unconstrained", "--timing-allow-fail", "--report", str(report),
        "--detailed-timing-report", "-q", "--log", str(raw / "nextpnr.log")],
       work / "nextpnr.out")  # fmt: skip

    cells = json.loads((raw / "yosys_stat.json").read_text())["design"]["num_cells_by_type"]
    rep = json.loads(report.read_text())
    # Keep the detailed report compressed (it is MBs); full Yosys logs stay in build/.
    with gzip.open(raw / "nextpnr_report.json.gz", "wt") as f:
        f.write(report.read_text())
    report.unlink()
    crit: dict = {}
    if rep.get("critical_paths"):
        path = rep["critical_paths"][0]
        steps = path.get("path", [])
        crit = {
            "from_clock": path.get("from"),
            "to_clock": path.get("to"),
            "start_cell": steps[0]["from"]["cell"] if steps else None,
            "end_cell": steps[-1]["to"]["cell"] if steps else None,
            "logic_ns": round(sum(st["delay"] for st in steps if st["type"] != "routing"), 3),
            "routing_ns": round(sum(st["delay"] for st in steps if st["type"] == "routing"), 3),
            "steps": len(steps),
        }
    summary = {
        "top": args.top,
        "S": args.S,
        "git_commit": commit,
        "device": DEVICE,
        "target_freq_mhz": args.freq,
        "nextpnr_seed": args.seed,
        "fmax_mhz": {clk: round(v["achieved"], 2) for clk, v in rep.get("fmax", {}).items()},
        "yosys_cells": {k: cells[k] for k in KEEP_CELLS if k in cells},
        "nextpnr_utilization": {
            k: v for k, v in rep.get("utilization", {}).items() if k in KEEP_UTIL
        },
        "harness": wrap_size,
        "critical_path": crit,
        "tools": {"yosys": tool_version(["yosys", "-V"]), "nextpnr": nextpnr},
        "script": "scripts/synth/ecp5.py",
    }
    out = REPO / "results" / "synth" / f"{name}.json"
    out.write_text(json.dumps(summary, indent=2) + "\n")
    print(f"synth: wrote {out.relative_to(REPO)}")
    show = ("fmax_mhz", "yosys_cells", "nextpnr_utilization", "critical_path")
    print(json.dumps({k: summary[k] for k in show}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
